// ============================================================================
// Dark-mode override generator (June 2025).
// The app has hundreds of hardcoded light-palette Tailwind classes
// (bg-emerald-50, text-amber-800, border-red-200, from-orange-50 ...).
// Instead of editing thousands of JSX class strings, this script scans the
// source, finds every such token actually used, and generates a `.dark`
// override block appended to app/globals.css:
//   • pale colored backgrounds  -> deep/muted translucent color of same family
//   • dark colored text (600-900) -> lighter tint of the same family
//   • pale colored borders      -> low-opacity same-family hairlines
//   • bg-white (+ opacity)      -> dark card surface
//   • neutral (slate/gray/...)  -> charcoal surfaces / light gray text
//   • gradient stops (from/via/to -50/-100/white) -> dark equivalents
// Re-run after adding new colored classes:  node scripts/gen-dark-overrides.mjs
// ============================================================================
import fs from 'fs'
import path from 'path'

const ROOT = '/app'
const GLOBALS = path.join(ROOT, 'app/globals.css')
const START = '/* ===== DARK MODE OVERRIDES (generated by scripts/gen-dark-overrides.mjs) — START ===== */'
const END = '/* ===== DARK MODE OVERRIDES (generated) — END ===== */'

// Tailwind v3 default palette (shades needed for remapping)
const PAL = {
  red: { 200: '#fecaca', 300: '#fca5a5', 400: '#f87171', 500: '#ef4444' },
  orange: { 200: '#fed7aa', 300: '#fdba74', 400: '#fb923c', 500: '#f97316' },
  amber: { 200: '#fde68a', 300: '#fcd34d', 400: '#fbbf24', 500: '#f59e0b' },
  yellow: { 200: '#fef08a', 300: '#fde047', 400: '#facc15', 500: '#eab308' },
  lime: { 200: '#d9f99d', 300: '#bef264', 400: '#a3e635', 500: '#84cc16' },
  green: { 200: '#bbf7d0', 300: '#86efac', 400: '#4ade80', 500: '#22c55e' },
  emerald: { 200: '#a7f3d0', 300: '#6ee7b7', 400: '#34d399', 500: '#10b981' },
  teal: { 200: '#99f6e4', 300: '#5eead4', 400: '#2dd4bf', 500: '#14b8a6' },
  cyan: { 200: '#a5f3fc', 300: '#67e8f9', 400: '#22d3ee', 500: '#06b6d4' },
  sky: { 200: '#bae6fd', 300: '#7dd3fc', 400: '#38bdf8', 500: '#0ea5e9' },
  blue: { 200: '#bfdbfe', 300: '#93c5fd', 400: '#60a5fa', 500: '#3b82f6' },
  indigo: { 200: '#c7d2fe', 300: '#a5b4fc', 400: '#818cf8', 500: '#6366f1' },
  violet: { 200: '#ddd6fe', 300: '#c4b5fd', 400: '#a78bfa', 500: '#8b5cf6' },
  purple: { 200: '#e9d5ff', 300: '#d8b4fe', 400: '#c084fc', 500: '#a855f7' },
  fuchsia: { 200: '#f5d0fe', 300: '#f0abfc', 400: '#e879f9', 500: '#d946ef' },
  pink: { 200: '#fbcfe8', 300: '#f9a8d4', 400: '#f472b6', 500: '#ec4899' },
  rose: { 200: '#fecdd3', 300: '#fda4af', 400: '#fb7185', 500: '#f43f5e' },
}
const NEUTRALS = ['slate', 'gray', 'zinc', 'neutral', 'stone']
// Charcoal surfaces (near-black, never pure black)
const NBG = { 50: '#1b1f26', 100: '#20242c', 200: '#2a2f38', 300: '#343a45' }
// Light gray text ramp (primary near-white, secondary mid-gray)
const NTEXT = { 500: '#98a4b3', 600: '#aab5c3', 700: '#c3cbd6', 800: '#dbe1e9', 900: '#eef1f5', 950: '#f4f6f9' }
// Subtle light hairlines, low opacity
const NBORDER = { 50: 'rgba(255,255,255,0.06)', 100: 'rgba(255,255,255,0.07)', 200: 'rgba(255,255,255,0.10)', 300: 'rgba(255,255,255,0.14)', 400: 'rgba(255,255,255,0.22)' }
const CARD = '#191d24'          // == hsl(220 18% 12%) — matches --card
const CARD_HOVER = '#232833'
const BG_PAGE = '#10131a'       // == hsl(220 20% 8%) — matches --background

const hexToRgb = (h) => {
  const s = h.replace('#', '')
  return [parseInt(s.slice(0, 2), 16), parseInt(s.slice(2, 4), 16), parseInt(s.slice(4, 6), 16)]
}
const rgba = (hex, a) => { const [r, g, b] = hexToRgb(hex); return `rgba(${r},${g},${b},${a})` }

// ---- collect tokens ----
const files = []
const walk = (dir) => {
  for (const e of fs.readdirSync(dir, { withFileTypes: true })) {
    const p = path.join(dir, e.name)
    if (e.isDirectory()) {
      if (['node_modules', '.next', 'api', 'ui'].includes(e.name)) continue
      walk(p)
    } else if (/\.(js|jsx)$/.test(e.name)) files.push(p)
  }
}
walk(path.join(ROOT, 'app'))
walk(path.join(ROOT, 'components'))

const TOKEN_RE = /(?:hover:|focus:|group-hover:)?(?:bg|text|border|from|via|to|divide)-(?:white|black|(?:slate|gray|zinc|neutral|stone|red|orange|amber|yellow|lime|green|emerald|teal|cyan|sky|blue|indigo|violet|purple|fuchsia|pink|rose)-\d{2,3})(?:\/\d{1,3})?(?![\w-])/g
const tokens = new Set()
for (const f of files) {
  const src = fs.readFileSync(f, 'utf8')
  for (const m of src.matchAll(TOKEN_RE)) tokens.add(m[0])
}

// ---- build rules ----
const esc = (t) => t.replace(/[:/]/g, (m) => '\\' + m)
const rules = []
const push = (token, decl, pseudo = '') => {
  let sel
  if (token.startsWith('group-hover:')) sel = `.dark .group:hover .${esc(token)}`
  else if (token.startsWith('hover:')) sel = `.dark .${esc(token)}:hover`
  else if (token.startsWith('focus:')) sel = `.dark .${esc(token)}:focus`
  else sel = `.dark .${esc(token)}${pseudo}`
  rules.push(`${sel} { ${decl} }`)
}

for (const token of [...tokens].sort()) {
  const m = token.match(/^(hover:|focus:|group-hover:)?(bg|text|border|from|via|to|divide)-(white|black|([a-z]+)-(\d{2,3}))(\/(\d{1,3}))?$/)
  if (!m) continue
  const [, , util, colorFull, family, shadeStr, , alphaStr] = m
  const shade = shadeStr ? parseInt(shadeStr, 10) : null
  const alpha = alphaStr ? parseInt(alphaStr, 10) / 100 : 1
  const isWhite = colorFull === 'white'
  const isNeutral = NEUTRALS.includes(family)
  const pal = PAL[family]

  if (colorFull === 'black') continue // dark overlays are fine as-is

  // ---------- bg ----------
  if (util === 'bg') {
    if (isWhite) {
      const v = token.includes('hover:') ? CARD_HOVER : alpha < 1 ? rgba(CARD, alpha) : CARD
      push(token, `background-color: ${v};`)
    } else if (isNeutral) {
      if (shade > 300) continue
      if (token.includes('hover:')) {
        const a = { 50: 0.05, 100: 0.07, 200: 0.10, 300: 0.12 }[shade]
        push(token, `background-color: rgba(255,255,255,${a});`)
      } else push(token, `background-color: ${NBG[shade] || NBG[300]};`)
    } else if (pal) {
      if (shade > 200) continue // saturated bgs stay
      const base = { 50: 0.10, 100: 0.16, 200: 0.24 }[shade]
      const a = token.includes('hover:') ? Math.min(base + 0.06, 0.35) : base
      push(token, `background-color: ${rgba(pal[500], a * alpha)};`)
    }
    continue
  }

  // ---------- text ----------
  if (util === 'text') {
    if (isWhite) continue
    if (isNeutral) {
      if (shade < 500) continue // already light
      push(token, `color: ${NTEXT[shade] || NTEXT[900]};`)
    } else if (pal) {
      if (shade < 600 || shade > 900) continue // 950 often sits on saturated bg (badges) — keep
      const map = { 600: 400, 700: 300, 800: 300, 900: 200 }
      push(token, `color: ${pal[map[shade]]};`)
    }
    continue
  }

  // ---------- border / divide ----------
  if (util === 'border' || util === 'divide') {
    let v = null
    if (isWhite) v = 'rgba(255,255,255,0.12)'
    else if (isNeutral) { if (shade > 400) continue; v = NBORDER[shade] || NBORDER[400] }
    else if (pal) {
      if (shade > 400) continue // saturated borders stay
      const a = { 50: 0.20, 100: 0.25, 200: 0.32, 300: 0.42, 400: 0.55 }[shade]
      v = rgba(pal[400], a * alpha)
    }
    if (!v) continue
    if (util === 'divide') push(token, `border-color: ${v};`, ' > :not([hidden]) ~ :not([hidden])')
    else push(token, `border-color: ${v};`)
    continue
  }

  // ---------- gradient stops ----------
  if (util === 'from' || util === 'via' || util === 'to') {
    let v = null, rgb0 = null
    if (isWhite) { v = CARD; rgb0 = rgba(CARD, 0) }
    else if (isNeutral) { if (shade > 200) continue; v = NBG[shade]; rgb0 = rgba(NBG[shade], 0) }
    else if (pal) {
      if (shade > 100) continue
      const a = ({ 50: 0.12, 100: 0.18 }[shade]) * alpha
      v = rgba(pal[500], a); rgb0 = rgba(pal[500], 0)
    }
    if (!v) continue
    if (util === 'from') push(token, `--tw-gradient-from: ${v} var(--tw-gradient-from-position); --tw-gradient-to: ${rgb0} var(--tw-gradient-to-position); --tw-gradient-stops: var(--tw-gradient-from), var(--tw-gradient-to);`)
    else if (util === 'via') push(token, `--tw-gradient-to: ${rgb0} var(--tw-gradient-to-position); --tw-gradient-stops: var(--tw-gradient-from), ${v} var(--tw-gradient-via-position), var(--tw-gradient-to);`)
    else push(token, `--tw-gradient-to: ${v} var(--tw-gradient-to-position);`)
  }
}

// A few handcrafted safety rules
rules.push(`.dark body { background-color: ${BG_PAGE}; }`)
rules.push(`.dark ::selection { background-color: rgba(16,185,129,0.35); }`)

const block = `${START}\n/* ${rules.length} rules generated from ${tokens.size} tokens found in ${files.length} source files. */\n${rules.join('\n')}\n${END}\n`

let css = fs.readFileSync(GLOBALS, 'utf8')
const si = css.indexOf(START)
if (si !== -1) {
  const ei = css.indexOf(END) + END.length
  css = css.slice(0, si) + block + css.slice(ei + (css[ei] === '\n' ? 1 : 0))
} else {
  css = css.trimEnd() + '\n\n' + block
}
fs.writeFileSync(GLOBALS, css)
console.log(`OK: ${rules.length} dark override rules written to app/globals.css (${tokens.size} tokens, ${files.length} files scanned)`)
